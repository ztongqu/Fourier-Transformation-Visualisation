def general_formula() -> None:
    global coefficients, frequencies
    for i in frequencies:
        coefficients[i] = 0
    coefficients[1] = 180j

def manual_coefficients() -> None:
    global coefficients
    coefficients = letter_capital_i3
    output = ""
    for i in frequencies:
        try:
            if coefficients[i] != 0:
                output += str(coefficients[i]).replace("j", "i") + "e^" + str(i) + "iπt+"
            coefficients[i] *= 30
        except KeyError:
            coefficients[i] = 0

    print(output[:-1])

def square_wave_formula() -> None:
    global coefficients, frequencies
    for i in frequencies:
        if i & 1 == 1:
            coefficients[i] = 800j / i / cmath.pi
        else:
            coefficients[i] = 0

def seesaw_wave_formula() -> None:
    global coefficients, frequencies
    for i in frequencies:
        if i != 0:
            coefficients[i] = 400j / i / cmath.pi
        else:
            coefficients[i] = 0

def triangle_wave_formula() -> None:
    global coefficients, frequencies
    p: int = -1
    for i in frequencies:
        if i & 1 == 1:
            p *= p
            coefficients[i] = 1600 * p / (i**2 * cmath.pi**2)
        else:
            coefficients[i] = 0

